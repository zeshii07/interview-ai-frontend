import React, { useCallback, useState } from 'react';
import {
  View, Text, StyleSheet, ScrollView, TouchableOpacity, Alert, Share,
} from 'react-native';
import { Ionicons } from '@expo/vector-icons';
import { router } from 'expo-router';
import * as Sharing from 'expo-sharing';
import * as FileSystem from 'expo-file-system';

import { Colors, Spacing, FontSizes, Radius, Shadows } from '../../constants/theme';
import useInterviewFlowStore from '../../store/interviewFlowStore';
import useInterviewStore from '../../store/interviewStore';
import Button from '../../components/ui/Button';
import Badge from '../../components/ui/Badge';
import ScoreBreakdown from '../../components/ui/ScoreBreakdown';
import StrengthsWeaknesses from '../../components/ui/StrengthsWeaknesses';

export default function ReportScreen() {
  const flow = useInterviewFlowStore();
  const store = useInterviewStore();
  const [generating, setGenerating] = useState(false);

  const score = flow.results?.score ?? (
    store.sessionAnswerCount > 0
      ? store.sessionScoreTotal / store.sessionAnswerCount
      : 0
  );

  const handleDownloadPDF = useCallback(async () => {
    setGenerating(true);
    try {
      // Generate a simple text-based PDF report locally.
      // (For a full PDF, we'd call the backend PDF service — but for now
      // we generate a shareable text summary and let the user share it
      // via the native share sheet, which can save it to Files, mail it,
      // etc.)
      const date = new Date().toLocaleString();
      const questions = store.sessionQuestions || [];

      const reportLines = [
        'HIRELY INTERVIEW REPORT',
        '========================',
        '',
        `Date: ${date}`,
        `Type: ${flow.results?.type || 'General'}`,
        `Role: ${flow.results?.role || 'Software Engineer'}`,
        `Questions answered: ${flow.results?.questionCount || store.sessionAnswerCount}`,
        `Average score: ${score.toFixed(1)}/10`,
        '',
        'PER QUESTION BREAKDOWN',
        '-----------------------',
        ...questions.map((q, i) => {
          const qt = typeof q === 'string' ? q : q?.question || '';
          const s = Number(q?.feedback?.rating || 0);
          const cat = q?.category || 'General';
          return `\n${i + 1}. [${cat}] Score: ${s.toFixed(1)}/10\n   Q: ${qt}\n   A: ${(q?.feedback?.explanation || '').slice(0, 200)}`;
        }),
        '',
        'Generated by Hirely — your AI career companion.',
      ];

      const reportText = reportLines.join('\n');
      const fileUri = `${FileSystem.cacheDirectory}hirely-report-${Date.now()}.txt`;

      await FileSystem.writeAsStringAsync(fileUri, reportText, {
        encoding: FileSystem.EncodingType.UTF8,
      });

      if (await Sharing.isAvailableAsync()) {
        await Sharing.shareAsync(fileUri, {
          mimeType: 'text/plain',
          dialogTitle: 'Save or share your Hirely interview report',
        });
      } else {
        Alert.alert('Report generated', 'Sharing is not available on this device.');
      }
    } catch (err) {
      Alert.alert('Could not generate report', err?.message || 'Please try again.');
    } finally {
      setGenerating(false);
    }
  }, [flow.results, store.sessionQuestions, store.sessionAnswerCount, score]);

  const handleShare = useCallback(async () => {
    try {
      await Share.share({
        message: `My Hirely interview report — Score: ${score.toFixed(1)}/10. Generated by Hirely.`,
      });
    } catch {}
  }, [score]);

  const handleBack = () => router.back();

  return (
    <View style={styles.screen}>
      <View style={styles.header}>
        <TouchableOpacity onPress={handleBack} hitSlop={{ top: 12, bottom: 12, left: 12, right: 12 }}>
          <Ionicons name="arrow-back-outline" size={24} color={Colors.textPrimary} />
        </TouchableOpacity>
        <Text style={styles.headerTitle}>Detailed Report</Text>
        <TouchableOpacity onPress={handleShare} hitSlop={{ top: 12, bottom: 12, left: 12, right: 12 }}>
          <Ionicons name="share-outline" size={20} color={Colors.primary} />
        </TouchableOpacity>
      </View>

      <ScrollView
        contentContainerStyle={styles.scrollContent}
        showsVerticalScrollIndicator={false}
      >
        {/* Summary card */}
        <View style={styles.summaryCard}>
          <View style={styles.summaryRow}>
            <View>
              <Text style={styles.summaryLabel}>Score</Text>
              <Text style={styles.summaryScore}>{score.toFixed(1)}<Text style={styles.summaryMax}>/10</Text></Text>
            </View>
            <View style={styles.summaryMetaCol}>
              <Badge label={flow.results?.type || 'General'} variant="primary" size="md" />
              {flow.results?.role ? <Badge label={flow.results.role} variant="neutral" size="md" /> : null}
            </View>
          </View>
        </View>

        {/* Question-by-question breakdown */}
        <View style={styles.card}>
          <Text style={styles.sectionTitle}>Question-by-question</Text>
          {(store.sessionQuestions || []).map((q, i) => {
            const qt = typeof q === 'string' ? q : q?.question || '';
            const s = Number(q?.feedback?.rating || 0);
            const cat = q?.category || 'General';
            const explanation = q?.feedback?.explanation || q?.feedback?.feedback || '';
            return (
              <View key={i} style={styles.questionCard}>
                <View style={styles.questionHeader}>
                  <Text style={styles.questionNumber}>Q{i + 1}</Text>
                  <Badge label={cat} variant="neutral" size="sm" />
                  <View style={styles.questionScoreBadge}>
                    <Text style={styles.questionScoreText}>{s.toFixed(1)}/10</Text>
                  </View>
                </View>
                <Text style={styles.questionText}>{qt}</Text>
                {explanation ? (
                  <Text style={styles.questionExplanation}>{explanation}</Text>
                ) : null}
              </View>
            );
          })}
        </View>

        <View style={{ height: 100 }} />
      </ScrollView>

      <View style={styles.footer}>
        <Button
          label={generating ? 'Generating…' : 'Download report'}
          icon="download-outline"
          iconPosition="left"
          size="lg"
          fullWidth
          disabled={generating}
          onPress={handleDownloadPDF}
        />
      </View>
    </View>
  );
}

